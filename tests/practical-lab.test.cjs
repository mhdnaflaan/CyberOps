const assert=require('assert');
const fs=require('fs');
const vm=require('vm');
const code=fs.readFileSync(__dirname+'/../js/practical-lab.js','utf8');
const store={};
const context={window:{},localStorage:{getItem:k=>store[k]||null,setItem:(k,v)=>store[k]=v,removeItem:k=>delete store[k]},Date,JSON,Math};
vm.runInNewContext(code,context);
const lab=context.window.CyberOpsPracticalLab; let s=lab.load();
assert.equal(s.devices['DNS-01'],'down');
assert(lab.execute('map',s).ok);assert(s.flags.mapped);
assert(lab.execute('diagnose intranet',s).ok);assert(s.flags.diagnosed);
assert(lab.execute('service status dns',s).out.includes('STOPPED'));
assert(lab.execute('service start dns',s).ok);assert.equal(s.devices['DNS-01'],'up');
assert(lab.execute('verify intranet',s).ok);assert(s.flags.verified);
assert(!lab.execute('report fixed',s).ok,'short report must be rejected');
assert(lab.execute('report DNS service was stopped; restarted it and verified intranet resolution',s).ok);assert(s.flags.reported);
assert(lab.load().flags.reported,'state persists');
assert(!lab.execute('nmap 8.8.8.8',s).ok,'unsupported/out-of-scope real target command rejected');
console.log('CyberOps 8.4 practical lab tests passed.');
